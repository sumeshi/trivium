//! Deterministic Rust -> TypeScript wire contract generation.
use std::{env, fs, path::PathBuf};
use trivium_engine::{analysis, annotation, condition, jobs, models, ops};
use ts_rs::TS;

fn add<T: TS>(out: &mut String) {
    out.push_str("export ");
    for line in T::decl().lines() {
        out.push_str(line.trim_end());
        out.push('\n');
    }
}

fn main() -> Result<(), Box<dyn std::error::Error>> {
    let mut out = String::from("// Generated by cargo run -p trivium-engine --bin export_contracts. Do not edit.\n// Source integers/timestamps travel in Cell.text as strings; JSON counters are numbers.\n\n");
    macro_rules! emit { ($($ty:ty),+ $(,)?) => { $(add::<$ty>(&mut out);)+ }; }
    emit!(
        serde_json::Value,
        condition::Op,
        condition::GroupKind,
        condition::Condition,
        condition::Group,
        condition::Node,
        annotation::AnnotationPatch,
        models::ColumnMeta,
        models::ProjectMeta,
        models::ProjectSummary,
        models::ViewState,
        models::Cell,
        models::ProjectRow,
        models::ColorRule,
        models::IocEntry,
        models::LoadProjectResponse,
        models::FlagEntry,
        models::UpdateFlagResponse,
        ops::view::ViewStateLoad,
        ops::view::ViewStateRequest,
        ops::view::SaveViewStatePayload,
        ops::rows::QuerySpec,
        ops::rows::QueryRowsPayload,
        ops::rows::QueryRowsResponse,
        ops::rows::LocateRowPayload,
        ops::rows::LocateRowResponse,
        analysis::stats::ValueCount,
        analysis::stats::ColumnStats,
        analysis::histogram::HistogramBucket,
        analysis::histogram::HistogramFlags,
        analysis::histogram::HistogramRangeInfo,
        analysis::histogram::Histogram,
        analysis::time::TimeSpan,
        analysis::time::TimeAnalysis,
        ops::group::GroupTreeNode,
        ops::group::GroupTreeResponse,
        ops::bulk::BulkCount,
        ops::bulk::BulkApplied,
        ops::value_validation::ValidateConditionValuesPayload,
        ops::value_validation::ConditionValueValidation,
        ops::value_validation::ConditionValuesValidation,
        jobs::JobKind,
        jobs::JobInfo,
        jobs::JobProgress,
    );
    let path = PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../../src/lib/generated/engine.ts");
    if env::args().any(|arg| arg == "--check") {
        if fs::read_to_string(&path).ok().as_deref() != Some(out.as_str()) {
            return Err(
                "Generated engine.ts is stale. Run export_contracts without --check.".into(),
            );
        }
    } else {
        fs::create_dir_all(path.parent().unwrap())?;
        fs::write(path, out)?;
    }
    Ok(())
}
