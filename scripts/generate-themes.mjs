import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const destination = path.join(root, 'src/lib/themeCatalog.generated.ts');
const stylesheet = path.join(root, 'src/lib/themeCatalog.generated.css');

/** One JSON definition is enough to register a built-in theme. */
export function generateThemes({ check = false, directory = path.join(root, 'definitions/themes'),
  typescriptPath = destination, cssPath = stylesheet } = {}) {
  const base = { tokens: JSON.parse(readFileSync(path.join(root, 'definitions/theme-base.json'), 'utf8')) };
  const paletteKeys = new Set([...Object.keys(base.tokens), 'flag-safe-selected-border',
    'flag-suspicious-selected-border', 'flag-critical-selected-border']);
  const definitions = readdirSync(directory).filter(name => name.endsWith('.json')).sort().map(name => {
    const definition = JSON.parse(readFileSync(path.join(directory, name), 'utf8'));
    if (definition.version !== 1 || !/^[a-z][a-z0-9-]{0,47}$/.test(definition.id)
      || typeof definition.name !== 'string' || !definition.name.trim() || definition.name.length > 64
      || !Number.isInteger(definition.order) || !['light', 'dark'].includes(definition.mode)
      || typeof definition.pastel !== 'boolean' || !definition.tokens || Array.isArray(definition.tokens)) {
      throw new Error(`Invalid theme definition: ${name}`);
    }
    for (const [key, value] of Object.entries(definition.tokens)) {
      if (!paletteKeys.has(key)
        || typeof value !== 'string' || value.length > 180 || /[;{}]|url\s*\(|expression\s*\(/i.test(value)) {
        throw new Error(`Invalid palette token ${key} in ${name}`);
      }
      if (['bg', 'surface', 'surface-weak', 'surface-soft', 'surface-strong'].includes(key)
        && !/^#[\da-f]{6}$/i.test(value)) throw new Error(`Theme surface ${key} must be opaque in ${name}`);
    }
    return definition;
  }).sort((a, b) => a.order - b.order || a.id.localeCompare(b.id));
  if (new Set(definitions.map(definition => definition.id)).size !== definitions.length
    || !definitions.some(definition => definition.id === 'light')) throw new Error('Duplicate/missing theme IDs');
  const output = '// Generated by scripts/generate-themes.mjs; edit definitions/themes/*.json.\n'
    + 'export const BUILTIN_THEMES = ' + JSON.stringify(definitions, null, 2) + ' as const;\n';
  const declarations = definition => Object.entries(definition.tokens).map(([key, value]) => `  --${key}: ${value};`).join('\n');
  const css = '/* Generated by scripts/generate-themes.mjs; edit definitions/themes/*.json. */\n'
    + ':root {\n  color-scheme: light;\n' + declarations(base) + '\n}\n'
    + definitions.map(definition => `[data-theme="${definition.id}"] {\n  color-scheme: ${definition.mode};\n${declarations(definition)}\n}`).join('\n') + '\n';
  for (const [file, text] of [[typescriptPath, output], [cssPath, css]]) {
    let current = '';
    try { current = readFileSync(file, 'utf8'); } catch {}
    if (current === text) continue;
    if (check) throw new Error('Theme catalog is stale. Run node scripts/generate-themes.mjs.');
    writeFileSync(file, text);
  }
  return definitions;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  generateThemes({ check: process.argv.includes('--check') });
}
